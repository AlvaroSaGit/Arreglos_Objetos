// creamos un objeto llamado celular con las propiedades marca, modelo, año y estado.
let celular = {
    marca: "Samsung",
    modelo: "Galaxy S21",
    año: 2021,
    estado: "Nuevo"
}

// Mostramos cada propiedad del objeto celular en la consola de manera individual.
console.log("Marca:", celular.marca);
console.log("Modelo:", celular.modelo);
console.log("Año:", celular.año);
console.log("Estado:", celular.estado);